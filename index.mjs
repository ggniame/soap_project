import soap from 'soap';

// Your live WildFly WSDL URL (make sure WildFly is running!)
const wsdlUrl = 'http://localhost:8080/PhoneValidatorService-1.0-SNAPSHOT/PhoneValidatorService/PhoneValidator?wsdl';

async function runClient() {
    try {
        console.log("Connecting to SOAP service...");
        
        // 1. Initialize the client asynchronously
        const client = await soap.createClientAsync(wsdlUrl);

        // 2. Define arguments mapping to your method
        // (Note: Depending on how your Java method parameters are named, 
        // you can pass an object matching your service parameter or arg0)
        const args = {
            pNum: '0633378' 
        };

        // 3. Call the SOAP method using the async version generated by the node-soap library
        const result = await client.validatePhoneAsync(args);
        
        console.log('Response from server:', result);

    } catch (error) {
        console.error('An error occurred:', error);
    }
}

runClient();